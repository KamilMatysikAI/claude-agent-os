"""Generated views: `projects/dashboard.md` and a marker block inside `TODO.md`.

Both are deterministic functions of the task files. Never edit them by hand: the next run
overwrites `dashboard.md` and everything between the TODO.md markers. Text outside the
markers in TODO.md is never touched.
"""

from __future__ import annotations

import os
from datetime import date
from pathlib import Path

from . import core

MARK_START = "<!-- AGENTOS:START -->"
MARK_END = "<!-- AGENTOS:END -->"
GENERATED_PREFIX = "_Generated by agentos"


def _rel(ws: Path, path: Path) -> str:
    try:
        return path.relative_to(ws).as_posix()
    except ValueError:
        return path.as_posix()


def _link(ws: Path, task: core.Task, base: Path) -> str:
    """Markdown link relative to the file that contains it (works in any viewer)."""
    try:
        target_str = Path(os.path.relpath(task.path, base)).as_posix()
    except ValueError:  # different drive on Windows
        target_str = _rel(ws, task.path)
    label = f"{task.id} {task.title}".strip() if task.id else task.title
    return f"[{label}]({target_str.replace(' ', '%20')})"


def due_label(task: core.Task, today: date) -> tuple[int, str]:
    """(sort key, label). Overdue first, then by date, undated last."""
    due = core.parse_date(task.get("due"))
    if not due:
        return (10**6, "no due date")
    delta = (due - today).days
    if delta < 0:
        return (delta, f"**{-delta} day(s) overdue**")
    if delta == 0:
        return (0, "**today**")
    return (delta, f"due {due.isoformat()} (in {delta} day(s))")


def collect(snap: core.Snapshot, cfg: dict, today: date) -> dict:
    tasks = snap.tasks
    open_tasks = [t for t in tasks if t.status in core.OPEN_STATUSES]
    decisions = [t for t in open_tasks if t.s("type") == "decision" and not t.s("decision")]
    human = [t for t in open_tasks if t.is_human and t.s("type") != "decision"]
    blocked = [t for t in tasks if t.status == "blocked"]
    no_evidence = [t for t in tasks if t.status == "done" and not str(t.get("evidence")).strip()]
    sort = lambda t: (due_label(t, today)[0], t.project, t.id)  # noqa: E731
    wip = core.wip_counts(tasks)
    default_limit = cfg["projects"]["wip_limit"]
    projects = []
    slugs = sorted(set(snap.projects) | {t.project for t in tasks if t.project})
    for slug in slugs:
        own = [t for t in tasks if t.project == slug]
        counts = {s: sum(1 for t in own if t.status == s) for s in core.STATUSES}
        meta = snap.projects.get(slug)
        projects.append({
            "slug": slug,
            "name": str(meta.get("name")) if meta and meta.get("name") else slug,
            "status": snap.project_status(slug),
            "wip": wip.get(slug, 0),
            "limit": snap.wip_limit(slug, default_limit),
            "counts": counts,
        })
    return {
        "decisions": sorted(decisions, key=sort),
        "human": sorted(human, key=sort),
        "blocked": sorted(blocked, key=lambda t: (t.project, t.id)),
        "no_evidence": sorted(no_evidence, key=lambda t: (t.project, t.id)),
        "projects": projects,
    }


def _blocked_line(snap, ws, task, base) -> str:
    unblocker = str(task.get("unblocked_by")).strip()
    if not unblocker:
        return f"- {_link(ws, task, base)} — **no unblocking human task** (guard will create one)"
    other = snap.by_id(task.project, unblocker)
    if other is None:
        return f"- {_link(ws, task, base)} — unblocked by {unblocker} (**missing file**)"
    return f"- {_link(ws, task, base)} — unblocked by {_link(ws, other, base)} [{other.status}]"


def render_dashboard(snap: core.Snapshot, cfg: dict, today: date, stamp_text: str) -> str:
    ws = snap.workspace
    base = core.projects_dir(ws)
    data = collect(snap, cfg, today)
    owner = cfg.get("owner_name") or "Owner"
    lines = ["# Dashboard", "",
             f"{GENERATED_PREFIX} {stamp_text}. Do not edit — regenerate with "
             "`python -m agentos dashboard`._", ""]

    lines += [f"## Decisions waiting for {owner} ({len(data['decisions'])})", ""]
    lines += [f"- {_link(ws, t, base)} — {t.project or 'inbox'}, {due_label(t, today)[1]}"
              for t in data["decisions"]] or ["- none"]
    lines.append("")

    lines += [f"## Tasks for {owner} ({len(data['human'])})", ""]
    lines += [f"- {_link(ws, t, base)} — {t.project or 'inbox'}, {due_label(t, today)[1]}"
              for t in data["human"]] or ["- none"]
    lines.append("")

    lines += [f"## Blocked ({len(data['blocked'])})", ""]
    lines += [_blocked_line(snap, ws, t, base) for t in data["blocked"]] or ["- none"]
    lines.append("")

    lines += ["## Projects", "", "| Project | Status | WIP | todo | in progress | blocked | done |",
              "|---|---|---|---|---|---|---|"]
    for p in data["projects"]:
        c = p["counts"]
        wip = f"{p['wip']}/{p['limit']}" + (" **over limit**" if p["wip"] > p["limit"] else "")
        lines.append(f"| {p['name']} | {p['status']} | {wip} | {c['todo']} | "
                     f"{c['in_progress']} | {c['blocked']} | {c['done']} |")
    if not data["projects"]:
        lines.append("| — | | | | | | |")
    lines.append("")

    lines += [f"## Done without evidence ({len(data['no_evidence'])})", ""]
    lines += [f"- {_link(ws, t, base)} — add `evidence:` (path, link or test result)"
              for t in data["no_evidence"]] or ["- none"]
    lines.append("")
    if snap.errors:
        lines += ["## Unreadable files", ""] + [f"- {e}" for e in snap.errors] + [""]
    return "\n".join(lines)


def render_todo_block(snap: core.Snapshot, cfg: dict, today: date, stamp_text: str) -> str:
    ws = snap.workspace
    data = collect(snap, cfg, today)
    lines = [MARK_START, f"{GENERATED_PREFIX} {stamp_text}; edit the task files, not this block._", ""]
    if data["decisions"]:
        lines += ["**Decisions waiting:**"]
        lines += [f"- [ ] {_link(ws, t, ws)} — {due_label(t, today)[1]}" for t in data["decisions"]]
        lines.append("")
    lines += ["**Your tasks:**"]
    lines += [f"- [ ] {_link(ws, t, ws)} — {due_label(t, today)[1]}" for t in data["human"]] \
        or ["- nothing waiting for you"]
    if data["blocked"]:
        lines += ["", f"Blocked agent tasks: {len(data['blocked'])} (see projects/dashboard.md)."]
    lines.append(MARK_END)
    return "\n".join(lines)


def _strip_generated(text: str) -> str:
    return "\n".join(ln for ln in text.splitlines() if not ln.startswith(GENERATED_PREFIX))


def _write_if_changed(path: Path, text: str) -> bool:
    try:
        old = path.read_text(encoding="utf-8")
    except (OSError, UnicodeDecodeError):
        old = None
    if old is not None and _strip_generated(old) == _strip_generated(text):
        return False  # only the timestamp would change: keep mtime quiet
    core.write_text_atomic(path, text)
    return True


def update_todo(path: Path, block: str) -> bool:
    try:
        text = path.read_text(encoding="utf-8")
    except FileNotFoundError:
        text = "# TODO\n\n"
    start, end = text.find(MARK_START), text.find(MARK_END)
    if start != -1 and end != -1 and end > start:
        new = text[:start] + block + text[end + len(MARK_END):]
    else:
        new = text.rstrip("\n") + "\n\n" + block + "\n"
    return _write_if_changed(path, new)


def generate(workspace, cfg: dict | None = None, now=None) -> dict:
    ws = Path(workspace)
    cfg = cfg or core.load_config(ws)
    moment = now or core.now_local(cfg)
    snap = core.load_snapshot(ws)
    stamp_text = core.stamp(moment)
    dash_path = core.projects_dir(ws) / "dashboard.md"
    changed_dash = _write_if_changed(dash_path, render_dashboard(snap, cfg, moment.date(), stamp_text))
    changed_todo = update_todo(ws / "TODO.md", render_todo_block(snap, cfg, moment.date(), stamp_text))
    for err in snap.errors:
        core.log(ws, "dashboard", f"unreadable: {err}")
    return {"dashboard": str(dash_path), "dashboard_changed": changed_dash,
            "todo_changed": changed_todo, "tasks": len(snap.tasks), "errors": len(snap.errors)}
