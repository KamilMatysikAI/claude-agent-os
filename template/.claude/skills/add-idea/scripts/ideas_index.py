#!/usr/bin/env python3
"""Regenerate ideas/index.md from the idea files' frontmatter.

Usage:
    python .claude/skills/add-idea/scripts/ideas_index.py [--workspace PATH]

Reads every ideas/*.md (except index.md), groups by `status`, sorts by potential
(high > medium > low) then by `created`, and writes ideas/index.md. The index
is a generated view: never edit it by hand. Idea files are only read.
Stdlib only, no side effects at import time.
"""

from __future__ import annotations

import argparse
import datetime as dt
import sys
from pathlib import Path

STATUS_ORDER = [
    ("new", "New (to assess)"),
    ("analysing", "Analysing"),
    ("approved", "Approved, waiting to start"),
    ("in_progress", "In progress"),
    ("done", "Done"),
    ("rejected", "Rejected"),
]
POTENTIAL_RANK = {"high": 0, "medium": 1, "low": 2}
INDEX_NAME = "index.md"


def find_workspace(start: Path) -> Path | None:
    current = start.resolve()
    for candidate in (current, *current.parents):
        if (candidate / "agentos.toml").is_file():
            return candidate
    return None


def read_frontmatter(path: Path) -> dict[str, str]:
    """Minimal flat YAML frontmatter reader: `key: value` lines between --- markers."""
    data: dict[str, str] = {}
    try:
        lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    except OSError:
        return data
    if not lines or lines[0].strip() != "---":
        return data
    for line in lines[1:]:
        if line.strip() == "---":
            break
        if ":" not in line or line.startswith((" ", "\t", "#")):
            continue
        key, _, value = line.partition(":")
        value = value.split(" #", 1)[0].strip().strip("'\"")
        data[key.strip()] = value
    return data


def build_index(ideas_dir: Path) -> str:
    groups: dict[str, list[tuple[Path, dict]]] = {key: [] for key, _ in STATUS_ORDER}
    unknown: list[tuple[Path, dict]] = []
    for path in sorted(ideas_dir.glob("*.md")):
        if path.name == INDEX_NAME:
            continue
        meta = read_frontmatter(path)
        status = meta.get("status", "new") or "new"
        (groups[status] if status in groups else unknown).append((path, meta))

    lines = [
        "# Ideas",
        "",
        f"<!-- Generated by add-idea/scripts/ideas_index.py on {dt.datetime.now():%Y-%m-%d %H:%M}. Do not edit. -->",
        "",
    ]
    for key, heading in STATUS_ORDER:
        items = groups[key]
        if not items:
            continue
        items.sort(key=lambda item: (POTENTIAL_RANK.get(item[1].get("potential", ""), 3), item[1].get("created", "")))
        lines += [f"## {heading} ({len(items)})", ""]
        for path, meta in items:
            box = "x" if key in ("done", "rejected") else " "
            title = meta.get("title") or path.stem
            parts = [meta.get("category") or "other", f"potential {meta.get('potential') or '?'}",
                     f"effort {meta.get('effort') or '?'}"]
            if meta.get("project"):
                parts.append(f"project {meta['project']}")
            lines.append(f"- [{box}] [{title}]({path.name}) — " + " · ".join(parts))
        lines.append("")
    if unknown:
        lines += [f"## Unknown status ({len(unknown)})", ""]
        lines += [f"- [ ] [{m.get('title') or p.stem}]({p.name}) — status `{m.get('status')}`" for p, m in unknown]
        lines.append("")
    return "\n".join(lines)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description="Regenerate ideas/index.md.")
    parser.add_argument("--workspace", help="workspace root (default: walk up to agentos.toml)")
    args = parser.parse_args(argv)
    root = Path(args.workspace) if args.workspace else find_workspace(Path.cwd())
    if root is None:
        print("error: agentos.toml not found; pass --workspace", file=sys.stderr)
        return 2
    ideas_dir = root / "ideas"
    if not ideas_dir.is_dir():
        print(f"error: {ideas_dir} does not exist", file=sys.stderr)
        return 2
    (ideas_dir / INDEX_NAME).write_text(build_index(ideas_dir), encoding="utf-8")
    print(f"written: {ideas_dir / INDEX_NAME}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
